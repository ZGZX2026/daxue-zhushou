  /* ---------- 生成全部专业课程 meta（惰性缓存） ---------- */
  var majorMetas = {}, allCache = null;
  function buildMajorMetas(c, m) {
    var key = c + '-' + m;
    if (majorMetas[key]) return majorMetas[key];
    var col = COLLEGES[c], mj = col.m[m];
    var arr = mj.k.map(function (course, k) {
      var id = 'x' + (c + 1) + '-' + m + '-' + k;
      return {
        id: id, name: course.n, icon: iconOf(c, course.n),
        bg: COL_BG[c][(m + k) % COL_BG[c].length],
        college: c, major: m, topics: course.t.slice(), gen: 1
      };
    });
    majorMetas[key] = arr;
    return arr;
  }

  var metaIndex = null;
  function buildIndex() {
    if (metaIndex) return metaIndex;
    metaIndex = {};
    COLLEGES.forEach(function (col, c) {
      col.m.forEach(function (mj, m) {
        buildMajorMetas(c, m).forEach(function (mm) { metaIndex[mm.id] = mm; });
      });
    });
    return metaIndex;
  }

  /* ---------- 作用域：基础学院 / 某专业（同步替换 UH.META 内容） ---------- */
  var scope = null; // null=基础学院；{c,m}=专业
  function applyScope(sp) {
    scope = sp;
    var meta = window.UH.META;
    meta.length = 0;
    if (!sp) {
      BASE_META().forEach(function (x) { meta.push(x); });
    } else {
      buildMajorMetas(sp.c, sp.m).forEach(function (x) { meta.push(x); });
    }
    try {
      if (sp) localStorage.setItem('uh_scope', JSON.stringify(sp));
      else localStorage.removeItem('uh_scope');
    } catch (e) {}
    return scope;
  }
