  function scoreFact(fact, hay) {
    var kws = (fact[3] || '').split(/\s+/).filter(Boolean);
    var s = 0;
    kws.forEach(function (kw) { if (hay.indexOf(kw) >= 0) s += 3; });
    if (hay.indexOf(fact[2]) >= 0) s += 1;
    return s;
  }

